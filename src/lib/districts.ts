export interface District {
  /** 시도 코드 — 검색이 이 값으로 먼저 좁힙니다 */
  sido: Sido;
  /** 화면에 보여줄 이름 — 「부산 사상구」 */
  label: string;
  /**
   * 좁은 쪽 이름 — 「사상구」. 서버가 **프로그램 주소에 이 이름이 들어 있는지** 봅니다.
   * 시도 전체를 고른 경우에는 null입니다(시도 코드만으로 판정).
   */
  name: string | null;
}

/**
 * 시·도 17개가 먼저, 그 아래 시·군·구.
 *
 * **시도를 앞에 두는 이유** — 「부산」이라고 친 사람은 대개 부산 전체를 뜻합니다.
 * 시군구가 먼저 나오면 「부산 중구」가 위에 뜨는데, 그건 훨씬 좁은 조건입니다.
 */
export const DISTRICTS: readonly District[] = RAW.flatMap(
  ([sido, short, , districts]): District[] => [
    { sido, label: short, name: null },
    ...districts.map((d) => ({ sido, label: `${short} ${d}`, name: d })),
  ]
);

/**
 * 시도 코드 → 짧은 이름. 검색 응답이 알려주는 지역(`{ sido, name }`)에 붙여
 * 「부산 사상구」로 보여줄 때 씁니다.
 */
export const SIDO_LABEL: Readonly<Record<Sido, string>> = Object.fromEntries(
  RAW.map(([sido, short]) => [sido, short])
) as Record<Sido, string>;
