/**
 * 사람 이름을 화면에 보여줄 때 쓰는 규칙 (2026-09-11).
 *
 * **이런 규칙은 한 곳에만 둡니다.** 자리마다 따로 쓰면 「마이페이지에서는 윤상,
 * 상세 페이지에서는 윤」처럼 같은 사람이 화면마다 다르게 보입니다 — 12시간제
 * 변환(`time.ts`)을 한 곳에 모은 것과 같은 이유입니다.
 */

/** 이름이 비었을 때 쓰는 글자. 브랜드 한 글자입니다 */
const FALLBACK = "품";

/**
 * 사진 대신 쓰는 동그라미 안에 넣을 글자 — **맨 앞 한 글자만** (2026-09-11 팀 요청).
 *
 * 「윤상호」는 **윤**입니다. 그전에는 두 글자(「윤상」)를 넣었는데, 성과 이름 첫 자가
 * 붙어 **이름의 일부처럼 읽혔습니다.** 한 글자면 「누구인지 가리키는 표시」로 읽힙니다.
 *
 * **글자 수로 자르지 않고 글자 단위로 자릅니다**(`Array.from`). 이모지나 일부 문자는
 * 두 칸을 차지해서, 그냥 잘라내면 **깨진 네모**가 나옵니다.
 *
 * 앞뒤 공백은 버립니다 — 공백이 첫 글자가 되면 동그라미가 비어 보입니다.
 */
export function avatarInitial(name: string | null | undefined): string {
  const trimmed = (name ?? "").trim();
  if (trimmed === "") return FALLBACK;
  return Array.from(trimmed)[0] ?? FALLBACK;
}
